import { beforeEach, afterEach, expect, it, vi } from 'vitest'
import { NextRequest } from 'next/server'
const mocks = vi.hoisted(() => ({ auth: vi.fn(), service: vi.fn(), reserve: vi.fn(), complete: vi.fn(), create: vi.fn(), read: vi.fn() }))
vi.mock('../../src/lib/supabase/server', () => ({ authenticatedUser: mocks.auth }))
vi.mock('../../src/lib/supabase/admin', () => ({ createSupabaseAdminClient: mocks.service }))
vi.mock('../../app/billing/db-scope', () => ({ billingDatabaseScopeReady: () => true }))
vi.mock('../../src/lib/billing/youpi-link-ledger', async () => ({ ...await vi.importActual('../../src/lib/billing/youpi-link-ledger'), reserveLink: mocks.reserve, completeLink: mocks.complete }))
vi.mock('../../src/lib/billing/youpi-contract', async () => ({ ...await vi.importActual('../../src/lib/billing/youpi-contract'), createYoupiSession: mocks.create, readYoupiSession: mocks.read }))
import { POST } from '../../app/api/youpi/admin/invoices/[id]/session/route'
const id = '11111111-1111-4111-8111-111111111111', paymentId = '33333333-3333-4333-8333-333333333333'
const actor = '22222222-2222-4222-8222-222222222222'
const request = (origin = 'https://www.credonomics.in', site = 'same-origin') => new NextRequest('https://www.credonomics.in/api/youpi/admin/invoices/'+id+'/session', { method: 'POST', headers: { origin, 'sec-fetch-site': site } })
const call = (req = request()) => POST(req, { params: Promise.resolve({ id }) })
beforeEach(() => {
  vi.resetAllMocks()
  for (const name of ['YOUPI_BRIDGE_ENABLED','YOUPI_PAYMENT_LINK_ENABLED','YOUPI_LINK_LEDGER_APPROVED','YOUPI_SESSION_CREATION_APPROVED','YOUPI_LICENSE_CONFIRMED','YOUPI_SECURITY_REVIEW_APPROVED','BILLING_API_ENABLED']) vi.stubEnv(name,'true')
  vi.stubEnv('YOUPI_PUBLIC_SITE_ORIGIN','https://www.credonomics.in')
  vi.stubEnv('YOUPI_PAYMENT_LINK_SIGNING_KEY','4a'.repeat(32))
  vi.stubEnv('BILLING_ADMIN_USER_IDS',actor)
  vi.stubEnv('YOUPI_API_ORIGIN','https://api.example.org'); vi.stubEnv('YOUPI_CHECKOUT_ORIGIN','https://pay.example.org')
  vi.stubEnv('YOUPI_MERCHANT_ID',actor); vi.stubEnv('YOUPI_MERCHANT_KEY','synthetic-merchant-key-only-123456789')
  mocks.auth.mockResolvedValue({ user: { id: actor, app_metadata: { billing_admin: true } } })
  mocks.service.mockReturnValue({ rpc: async () => ({ data: { id, totalPaise: 50000, paidPaise: 0, status: 'UNPAID', invoiceNumber: '1200' }, error: null }) })
  mocks.reserve.mockResolvedValue({ decision: 'CREATE', issuedAt: Date.now() })
  mocks.create.mockResolvedValue({ paymentId, status: 'INITIATED' })
  mocks.read.mockResolvedValue({ paymentId, status: 'ACTIVE' })
  mocks.complete.mockResolvedValue(undefined)
})
afterEach(() => vi.unstubAllEnvs())
it('denies disabled ledger, cross-origin and non-admin requests before gateway calls', async () => {
  vi.stubEnv('YOUPI_LINK_LEDGER_APPROVED','false'); expect((await call()).status).toBe(503)
  vi.stubEnv('YOUPI_LINK_LEDGER_APPROVED','true'); expect((await call(request('https://evil.test'))).status).toBe(403)
  expect((await call(request('https://www.credonomics.in','cross-site'))).status).toBe(403)
  mocks.auth.mockResolvedValue({ user: { id: actor, user_metadata: { billing_admin: true } } })
  expect((await call()).status).toBe(403)
  expect(mocks.create).not.toHaveBeenCalled()
})
it('reuses saved session, verifies owner state and persists before exposing link', async () => {
  mocks.reserve.mockResolvedValue({ decision: 'REUSE', paymentId, issuedAt: Date.now() })
  const res = await call()
  expect(res.status).toBe(200)
  expect(mocks.create).not.toHaveBeenCalled()
  expect(mocks.read).toHaveBeenCalledOnce(); expect(mocks.complete).toHaveBeenCalledOnce()
  expect(await res.json()).toMatchObject({ settlement: 'NOT_VERIFIED', gatewayStatus: 'ACTIVE' })
})
it('does not expose links on reservation conflict, gateway status failure or failed persistence', async () => {
  mocks.reserve.mockRejectedValueOnce(Error('pending'))
  expect((await call()).status).toBe(503); expect(mocks.create).not.toHaveBeenCalled()
  mocks.read.mockRejectedValueOnce(Error('already SUCCESS'))
  expect((await call()).status).toBe(503)
  mocks.complete.mockRejectedValueOnce(Error('offline'))
  const res = await call(); expect(res.status).toBe(503)
  expect(JSON.stringify(await res.json())).not.toContain('/pay/i/')
})
