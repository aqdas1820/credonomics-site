import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const inputDir = path.join(root, 'public', 'data', 'ipo', 'verified')
const outputTs = path.join(root, 'app', 'data', 'verified-ipos.generated.ts')

const files = fs.existsSync(inputDir)
  ? fs.readdirSync(inputDir).filter((name) => name.endsWith('.json') && !name.startsWith('_'))
  : []

const records = []
let latest = null

for (const file of files) {
  const full = path.join(inputDir, file)
  const data = JSON.parse(fs.readFileSync(full, 'utf8'))
  records.push(data)
  if (data.lastVerified && (!latest || data.lastVerified > latest)) latest = data.lastVerified
}

records.sort((a, b) => a.companyName.localeCompare(b.companyName))

const ts = `// AUTO-GENERATED by scripts/ipo/build-verified-ipos.mjs.
// Do not hand-edit. Edit public/data/ipo/verified/*.json and rebuild.

import type { VerifiedIpoRecord } from './ipo-types'

export const VERIFIED_IPO_DATA_DATE = ${JSON.stringify(latest)} as string | null
export const verifiedIpos: VerifiedIpoRecord[] = ${JSON.stringify(records, null, 2)}
`

fs.writeFileSync(outputTs, ts, 'utf8')
console.log(`Built ${records.length} verified IPO record(s).`)
