import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

const root = process.cwd()
const autoPath = path.join(root, 'public', 'data', 'cards', 'auto-catalog.json')
const verifiedPath = path.join(root, 'public', 'data', 'cards', 'verified-index.json')
const outputJson = path.join(root, 'public', 'data', 'cards', 'review-queue.json')
const outputTs = path.join(root, 'app', 'data', 'card-review-queue.generated.ts')

const readJson = (file, fallback) => {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')) } catch { return fallback }
}

const normalize = (value = '') =>
  value.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, ' ').trim()

const auto = readJson(autoPath, { records: [] })
const verified = readJson(verifiedPath, { records: [] })
const now = new Date()

const exact = new Map(
  verified.records.map((record) => [
    `${normalize(record.issuer)}|${normalize(record.name)}`,
    record,
  ]),
)

const items = []

for (const record of auto.records || []) {
  const key = `${normalize(record.issuer)}|${normalize(record.name)}`
  const match = exact.get(key)

  if (!match) {
    items.push({
      id: crypto.createHash('sha1').update(`new|${key}`).digest('hex').slice(0, 12),
      type: 'new-card-candidate',
      issuer: record.issuer,
      name: record.name,
      sourceUrl: record.sourceUrl,
      message: 'Official-source discovery record is not yet normalized in the verified ranking database.',
    })
    continue
  }

  const detectedFee = record.annualFee ?? record.renewalFee
  if (
    detectedFee !== undefined &&
    Number.isFinite(Number(detectedFee)) &&
    Math.abs(Number(detectedFee) - Number(match.annualFeeRupees || 0)) >= 50
  ) {
    items.push({
      id: crypto.createHash('sha1').update(`fee|${key}|${detectedFee}`).digest('hex').slice(0, 12),
      type: 'possible-fee-change',
      issuer: record.issuer,
      name: record.name,
      sourceUrl: record.sourceUrl,
      message: `Automated discovery detected fee ₹${Number(detectedFee).toLocaleString('en-IN')} versus verified ₹${Number(match.annualFeeRupees || 0).toLocaleString('en-IN')}. Human review required.`,
    })
  }
}

for (const record of verified.records || []) {
  const checked = new Date(`${record.verifiedAt}T00:00:00Z`)
  const ageDays = Math.floor((now.getTime() - checked.getTime()) / 86400000)
  if (Number.isFinite(ageDays) && ageDays > 45) {
    items.push({
      id: crypto.createHash('sha1').update(`due|${record.id}|${record.verifiedAt}`).digest('hex').slice(0, 12),
      type: 'review-due',
      issuer: record.issuer,
      name: record.name,
      sourceUrl: record.sourceUrl,
      message: `Verified record is ${ageDays} days old and is due for source review.`,
    })
  }
}

const unique = []
const seen = new Set()
for (const item of items) {
  const key = `${item.type}|${normalize(item.issuer)}|${normalize(item.name)}`
  if (seen.has(key)) continue
  seen.add(key)
  unique.push(item)
}

const sorted = unique
  .sort((a, b) => {
    const order = { 'possible-fee-change': 0, 'review-due': 1, 'new-card-candidate': 2 }
    return order[a.type] - order[b.type] || a.issuer.localeCompare(b.issuer) || a.name.localeCompare(b.name)
  })
  .slice(0, 250)

const meta = {
  generatedAt: now.toISOString(),
  itemCount: sorted.length,
  newCardCandidates: sorted.filter((item) => item.type === 'new-card-candidate').length,
  possibleFeeChanges: sorted.filter((item) => item.type === 'possible-fee-change').length,
  reviewDue: sorted.filter((item) => item.type === 'review-due').length,
}

fs.writeFileSync(outputJson, JSON.stringify({ meta, items: sorted }, null, 2) + '\n', 'utf8')

const ts = `// AUTO-GENERATED by scripts/cards/build-card-review-queue.mjs

export type CardReviewQueueItem = {
  id: string
  type: 'new-card-candidate' | 'possible-fee-change' | 'review-due'
  issuer: string
  name: string
  sourceUrl?: string
  message: string
}

export const cardReviewQueueMeta = ${JSON.stringify(meta, null, 2)} as const

export const cardReviewQueue: CardReviewQueueItem[] = ${JSON.stringify(sorted, null, 2)}
`
fs.writeFileSync(outputTs, ts, 'utf8')

console.log(`Review queue generated: ${meta.itemCount} item(s)`)
console.log(`  New candidates: ${meta.newCardCandidates}`)
console.log(`  Possible fee changes: ${meta.possibleFeeChanges}`)
console.log(`  Review due: ${meta.reviewDue}`)
